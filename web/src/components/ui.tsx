/** Chart / table switch: every chart has a table view. */
export function ViewToggle({ value, onChange }: { value: "chart" | "table"; onChange: (v: "chart" | "table") => void }) {
  return (
    <div className="seg" role="group" aria-label="View">
      {(["chart", "table"] as const).map((v) => (
        <button key={v} aria-pressed={value === v} onClick={() => onChange(v)}>
          {v === "chart" ? "Chart" : "Table"}
        </button>
      ))}
    </div>
  );
}

export function Loading({ loading, children }: { loading: boolean; children: ReactNode }) {
  return <div className={`loading${loading ? " is-loading" : ""}`} aria-busy={loading}>{children}</div>;
}

/** Width of an element, tracked with ResizeObserver. */
export function useWidth<T extends HTMLElement>(): [React.RefObject<T>, number] {
  const ref = useRef<T>(null);
  const [w, setW] = useState(0);
  useLayoutEffect(() => {
    if (!ref.current) return;
    // measure now, so charts draw on first paint instead of waiting for the observer
    setW(Math.floor(ref.current.getBoundingClientRect().width));
    const ro = new ResizeObserver(([e]) => setW(Math.floor(e.contentRect.width)));
    ro.observe(ref.current);
    return () => ro.disconnect();
  }, []);
  return [ref, w];
}

export function HeroAvatar({ src, name, size = 20 }: { src: string | null; name: string; size?: number }) {
  return src ? (
    <img src={src} alt="" width={size} height={size} loading="lazy"
         style={{ borderRadius: 4, objectFit: "cover", verticalAlign: "middle", background: "var(--surface-2)" }} />
  ) : (
    <span aria-hidden style={{
      display: "inline-grid", placeItems: "center", width: size, height: size, borderRadius: 4,
      background: "var(--surface-2)", color: "var(--muted)", fontSize: size * 0.5, verticalAlign: "middle",
    }}>{name.replace(/^Hero /, "").slice(0, 2)}</span>
  );
}
