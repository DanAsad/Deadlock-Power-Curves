"""List every table in the data lake and write its columns to schema.md.

Run from the repo root:  python -m pipeline.explore_schema

Sample rows are printed transposed with long values cut, because match_player
has ~180 columns, many of them per-minute arrays.
"""
from pathlib import Path

from pipeline.lake import connect

TIME_HINTS = ("time_stamp", "timestamp_s", "stats.", "snapshot", "per_minute", "_time_s")
NOTES = """## Findings (checked 2026-11-10)

- There is no `match_info` table. `match_player` is denormalised: one row per
  player per match, with match-level fields (`start_time`, `duration_s`,
  `match_mode`, `game_mode`, `winning_team`, badges) repeated on every row.
- Normal 6v6 = `game_mode = 'Normal'`; queue = `match_mode` ('Ranked' / 'Unranked').
- Rank: `average_badge` (badge = tier*10 + subtier, e.g. 53 = Ritualist 3) is set
  for Ranked matches only. `average_badge_team0/1` are always 0 in recent data.
- `won` matches `team = winning_team` on every row checked.
- ~0.002% duplicate (match_id, hero_id) rows; ~1% of matches have <12 player
  rows (partial ingest). The pipeline keeps full 12-player matches only.
- No patch column (`game_mode_version` is constant); patches are defined by
  date in `pipeline/config.py`.
- **Per-player time series exist**: `stats.time_stamp_s` with matching
  `stats.net_worth`, `stats.kills`, `stats.deaths`, ... arrays. Phase 2 training
  data can come from the lake, no replays needed. Snapshots are not per minute:
  every 3 min to 15:00, then every 5 min, plus one at game end (e.g.
  180, 360, ..., 900, 1200, 1500, ..., 2471), so interpolate onto a fixed grid.
"""
OUT = Path(__file__).resolve().parent.parent / "schema.md"


def _cut(v, n=70):
    s = str(v).replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    con = connect()
    tables = con.execute("""
        SELECT schema_name, table_name FROM duckdb_tables()
        WHERE database_name = 'dl' ORDER BY schema_name, table_name
    """).fetchall()

    lines = ["# Deadlock data lake schema\n",
             "Generated by `python -m pipeline.explore_schema`. Source: "
             "https://data.deadlock-api.com/v1/manifest.json\n", NOTES]
    flagged = []
    for schema, table in tables:
        full = f"dl.{schema}.{table}"
        cols = con.execute(f"DESCRIBE {full}").fetchall()
        # newest rows only: avoids scanning the whole table for a 1-row sample
        has_time = any(c[0] == "start_time" for c in cols)
        where = "WHERE start_time >= now() - INTERVAL 1 DAY" if has_time else ""
        sample = con.execute(f"SELECT * FROM {full} {where} LIMIT 1").fetchall()
        row = sample[0] if sample else [None] * len(cols)

        lines += [f"## {full}\n", "| column | type | example |", "|---|---|---|"]
        for (name, ctype, *_), val in zip(cols, row):
            lines.append(f"| {name} | {_cut(ctype, 60)} | {_cut(val)} |")
            if any(h in name.lower() for h in TIME_HINTS):
                flagged.append(f"{full}.{name} ({_cut(ctype, 40)})")
        lines.append("")
        print(f"{full}: {len(cols)} columns", flush=True)

    lines.append("## Possible time-series columns (Phase 2)\n")
    lines += [f"- {f}" for f in flagged] or ["- none found"]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {OUT} ({len(tables)} tables). Time-series candidates: {len(flagged)}")


if __name__ == "__main__":
    main()
